#pragma once

#include<memory>
#include<vector>
#include"execution_result.hpp"
#include"order.hpp"
#include"pg_connection.hpp"

namespace matching_engine{

// Отображает Order/OrderChange на таблицу orders и обратно. О JSON, argv
// и об остальных слоях приложения ничего не знает — только предметная
// область и переданное соединение.
//
// Соединение репозиторий получает параметром на каждый вызов и нигде не
// хранит полем: у класса нет ни поля-ссылки, ни поля-указателя на
// PgConnection. Это осознанное решение: PgConnection
// перемещаем (REQ-RAII-04), и хранимая репозиторием ссылка могла бы
// пережить перемещение исходного соединения и остаться указывающей на уже
// опустевший объект. Раз хранить нечего, сценарий "соединение переместили,
// пока где-то ещё жива ссылка на него от репозитория" исключён по
// конструкции, а не по договорённости: он требует поля, а поля нет.
//
// Границей транзакции репозиторий не управляет вообще — ни начало, ни
// завершение, ни откат он не выполняет; это решает вызывающий код
// (PgTransaction).
class OrderRepository{
public:
    // INSERT ... ON CONFLICT (order_id) DO UPDATE — одна операция и на
    // создание новой заявки, и на обновление существующей, и на отметку
    // отменённой (статус берётся из change.status, отдельного метода нет).
    // change.price == std::nullopt записывается как SQL NULL — так
    // сохраняется рыночная заявка.
    void save(PgConnection& connection, const OrderChange& change);

    // Пакетная запись (REQ-OPT-03): многострочный INSERT ...
    // ON CONFLICT DO UPDATE на весь список изменений, за один или несколько
    // execute() (см. sql_batch_insert.hpp — свёрнутый список режется по
    // числу строк, если иначе запрос превысил бы протокольный предел
    // параметров PostgreSQL). changes может содержать несколько записей с
    // одним и тем же order_id (одну заявку может задеть несколько команд
    // пакета, а MODIFY кладёт в ExecutionResult сразу два снимка одной
    // заявки) — PostgreSQL не может обновить одну строку дважды в одном
    // ON CONFLICT DO UPDATE (ошибка 21000), поэтому перед построением
    // запроса changes сворачивается по order_id, и побеждает последняя
    // запись — тот же порядок победителя, что и в save(), вызванном
    // последовательно (execution_result.hpp: "список упорядочен по времени
    // мутации... побеждает последняя запись"). Пустой список — no-op, ни один
    // запрос не выполняется. Обычный execute(), не executePrepared(): форма
    // запроса зависит от числа строк после свёртки, готовить её впрок незачем.
    void saveBatch(PgConnection& connection, const std::vector<OrderChange>& changes);

    // Активные заявки (OPEN, PARTIALLY_FILLED), строго в порядке
    // возрастания sequence_number — от этого порядка зависит сохранение
    // Price-Time Priority после перезапуска. Фильтрация по статусу сделана
    // в SQL, а не через Order::isFilled(): та смотрит только на остаток и
    // для отменённой заявки с нулевым остатком вернула бы true.
    std::vector<std::shared_ptr<Order>> loadActive(PgConnection& connection);

    // Максимум sequence_number по ВСЕЙ таблице orders, а не только по
    // активным заявкам, которые возвращает loadActive(). Нужен для восстановления SequenceGenerator при старте:
    // если взять максимум только по активным, исполненная или отменённая
    // заявка с бо́льшим номером останется невидимой, и первая же вставка
    // после старта столкнётся с UNIQUE на orders.sequence_number. Пустая
    // таблица — штатный случай первого запуска, возвращает 0.
    long long maxSequenceNumber(PgConnection& connection);
};

}
