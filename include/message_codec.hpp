#pragma once

#include <array>
#include <cstddef>
#include <cstdint>
#include <string>

namespace matching_engine {

// Заголовок кадра сетевого протокола: 4 байта uint32_t в сетевом порядке
// байт, содержащие длину полезной нагрузки
// (docs/task4/02-network-protocol.md, раздел 1).
constexpr std::size_t kFrameHeaderSize = 4;

// Собирает и разбирает кадр сетевого протокола: 4 байта длины полезной
// нагрузки в сетевом порядке байт, затем сама полезная нагрузка. Кодек
// работает с буферами в памяти, ничего не знает ни о сокетах, ни о
// Boost.Asio, ни о содержимом полезной нагрузки — для него это
// непрозрачные байты.
class MessageCodec {
public:
    // maxPayloadSize — верхняя граница длины полезной нагрузки, которую
    // decodeHeader готов принять. Значение приходит из конфигурации
    // (server.max_message_size) и передаётся вызывающей стороной, а не
    // зашивается константой внутри кодека.
    explicit MessageCodec(std::size_t maxPayloadSize);

    // Строит готовый кадр: заголовок (длина payload в сетевом порядке) и
    // сам payload следом.
    //
    // Бросает MessageTooLargeError, если payload.size() больше
    // maxPayloadSize, — до сужения размера к uint32_t заголовка. Без этой
    // проверки кодек на стороне сервера и кодек на стороне клиента судили
    // бы о допустимости кадра по-разному, а тело больше 4 ГиБ записало бы в
    // заголовок остаток по модулю 2^32.
    std::string encode(const std::string& payload) const;

    // Разбирает заголовок кадра и возвращает длину полезной нагрузки.
    //
    // Бросает MessageTooLargeError, если объявленный размер больше
    // maxPayloadSize, — до того, как вызывающая сторона выделит память под
    // тело кадра.
    //
    // Нулевая длина заголовком не отвергается: кадр с пустой полезной
    // нагрузкой корректен на уровне кадра (позиция следующего кадра в
    // потоке известна точно). Судьбу пустой полезной нагрузки решает
    // разбор её содержимого выше по стеку, а не кодек
    // (docs/task4/02-network-protocol.md, раздел 1.2).
    std::uint32_t decodeHeader(const std::array<char, kFrameHeaderSize>& header) const;

private:
    std::size_t maxPayloadSize_;
};

}
