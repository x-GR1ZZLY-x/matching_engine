#pragma once

#include <string>

namespace matching_engine {

// Слой между Session и обработкой конкретной команды (REQ-NET-11, план
// ДЗ-4 раздел 1.6): Session не знает, как устроена книга заявок, — она
// передаёт сюда уже отделённую кодеком полезную нагрузку одного кадра и
// получает назад готовую строку JSON-ответа. Ни о сокетах, ни об Asio,
// ни о формате кадра этот класс не знает — с его точки зрения запрос уже
// стал обычной строкой.
//
// В этой задаче маршрутизация минимальна: PING — служебная команда
// транспортного уровня (у неё нет command_id, она не идёт в БД и не
// касается книги, docs/task4/02-network-protocol.md, раздел 2) и потому
// обрабатывается прямо здесь, минуя CommandParser. Любой другой тип —
// такая же ошибка пользователя, как и неизвестная команда: команды
// предметной области (ADD/CANCEL/MODIFY/PRINT) подключаются в задаче 05
// без изменения интерфейса этого класса и без переписывания Session.
class RequestRouter {
public:
    // Разбирает payload как JSON и маршрутизирует по полю "type". Ошибка
    // пользователя (не JSON, payload не объект, поле "type" отсутствует
    // или не строка, неизвестный тип) не бросает исключение — превращается
    // в обычный ответ {"status":"ERROR","error":"INVALID_REQUEST",...}
    // (docs/task4/02-network-protocol.md, раздел 3.5). Соединение эта
    // ошибка не закрывает — решение об этом принимает Session.
    std::string handle(const std::string& payload) const;
};

}
