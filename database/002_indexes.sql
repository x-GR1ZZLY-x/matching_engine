-- Индексы под запросы из REQ-DB-08. Выполняется после 001_init.sql — таблицы
-- уже должны существовать.

-- Заявка по order_id и команда по command_id уже покрыты первичными ключами
-- из 001_init.sql, отдельных индексов под них заводить не нужно.

-- Восстановление книги при старте читает только активные заявки (OPEN и
-- PARTIALLY_FILLED) в порядке sequence_number, чтобы сохранить Price-Time
-- Priority. Индекс частичный: исполненные и отменённые заявки со временем
-- составят основную массу таблицы orders, а этот запрос их не читает —
-- незачем раздувать индекс записями, которые в него никогда не попадут.
CREATE INDEX IF NOT EXISTS idx_orders_active_sequence
    ON orders (sequence_number)
    WHERE status IN ('OPEN', 'PARTIALLY_FILLED');
